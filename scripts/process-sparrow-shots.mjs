/**
 * Converts Sparrow product screenshots to hashed WebP and writes the manifest
 * the case study imports.
 *
 * These are Sparrow's own published product screenshots, pulled from
 * docs.sparrowapp.dev — Sparrow is Techdome's product, and the docs are where
 * its real UI is publicly documented. The alternative was fabricating screens,
 * which the brief rules out.
 *
 * The manifest records each image's real dimensions, so the page can frame
 * every shot at its own aspect ratio instead of cropping a 1.91-wide app
 * screenshot into a 16:10 hole.
 *
 *   node scripts/process-sparrow-shots.mjs <png-dir>
 */
import crypto from "crypto";
import fs from "fs";
import path from "path";
import sharp from "sharp";

const SRC = process.argv[2];
if (!SRC) throw new Error("usage: node scripts/process-sparrow-shots.mjs <png-dir>");

const OUT_DIR = "public/images/v3/sparrow";
const MANIFEST = "src/content/sparrow-shots.ts";
const PUBLIC_PREFIX = "/images/v3/sparrow";
const WIDTH = 2160;

fs.mkdirSync(OUT_DIR, { recursive: true });
for (const f of fs.readdirSync(OUT_DIR)) {
  if (f.endsWith(".webp")) fs.unlinkSync(path.join(OUT_DIR, f));
}

/** Source filename -> logical name used in the page. */
const NAMES = {
  "RESTAPI1.png": "api-testing",
  "RESTAPI4.png": "request-body",
  "RESTAPI-ASSERTIONS1.png": "assertions",
  "Hub1.png": "hub",
  "Hub3.png": "hub-members",
  "Hub5.png": "hub-settings",
  "Workspace1.png": "workspace",
  "Workspace3.png": "workspace-manage",
  "Collections1.png": "collections",
  "Testflows1.png": "test-flows",
  "SparrowMarketplace_Home.png": "marketplace",
  "PublicWorkspaces_ShareWorkspace.png": "share-workspace",
  "Firstworkspace1.png": "first-workspace",
  "AddMockCollection.png": "mock-server",
  "IntroductionToSparrow.png": "overview",
};

const entries = [];
let total = 0;

for (const file of Object.keys(NAMES)) {
  const full = path.join(SRC, file);
  if (!fs.existsSync(full)) {
    console.log(`skip (missing): ${file}`);
    continue;
  }
  const name = NAMES[file];
  const pipeline = sharp(full).resize({ width: WIDTH, withoutEnlargement: true });
  const buf = await pipeline.webp({ quality: 82, effort: 6 }).toBuffer();
  const meta = await sharp(buf).metadata();

  const hash = crypto.createHash("sha256").update(buf).digest("hex").slice(0, 8);
  const filename = `${name}.${hash}.webp`;
  fs.writeFileSync(path.join(OUT_DIR, filename), buf);

  entries.push({ name, src: `${PUBLIC_PREFIX}/${filename}`, w: meta.width, h: meta.height });
  total += buf.length;
  console.log(
    `${name.padEnd(18)} ${meta.width}x${meta.height}  ${(buf.length / 1024).toFixed(0)}KB  ${filename}`
  );
}

const body = `/**
 * Sparrow product screens, by logical name.
 *
 * Generated by \`scripts/process-sparrow-shots.mjs\` — do not hand-edit.
 *
 * \`w\`/\`h\` are the real pixel dimensions. The case study frames each shot at
 * its own ratio from these, because Sparrow's app screenshots are about 1.91
 * wide and cropping them into a 16:10 frame would cut the panels off both
 * sides — and the panel layout is the thing the case study is about.
 *
 * The hash in each filename is the file's own content, so replacing a screen
 * changes its URL and no cache can serve the previous one.
 */
export type SparrowShot = {
  src: string;
  w: number;
  h: number;
};

export const sparrowShots = {
${entries.map((e) => `  "${e.name}": { src: "${e.src}", w: ${e.w}, h: ${e.h} },`).join("\n")}
} as const satisfies Record<string, SparrowShot>;

export type SparrowShotName = keyof typeof sparrowShots;
`;

fs.writeFileSync(MANIFEST, body);
console.log("---");
console.log(`${entries.length} screens, ${(total / 1024 / 1024).toFixed(2)}MB`);
console.log(`wrote ${MANIFEST}`);
