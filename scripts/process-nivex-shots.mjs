/**
 * Converts captured Nivex PNGs to WebP under content-hashed filenames, and
 * writes the name -> path map the case study imports.
 *
 * The hash is the point. These screens get re-captured — light mode instead of
 * dark, a screen re-shot after a UI change — and under a stable filename that
 * replacement is invisible: Next's image optimizer keeps serving its cached
 * render from `.next/cache/images`, and browsers keep serving theirs, both
 * keyed on a URL that did not change. A new hash is a new URL, so nothing can
 * serve the old bytes. It also lets these carry the immutable year-long cache
 * header from next.config.ts.
 *
 *   node scripts/process-nivex-shots.mjs <png-dir>
 */
import crypto from "crypto";
import fs from "fs";
import path from "path";
import sharp from "sharp";

const SRC = process.argv[2];
if (!SRC) throw new Error("usage: node scripts/process-nivex-shots.mjs <png-dir>");

const OUT_DIR = "public/images/v3/nivex";
const MANIFEST = "src/content/nivex-shots.ts";
const PUBLIC_PREFIX = "/images/v3/nivex";

/** 2x for the widest slot the page shows a screen in (~1080 CSS px). */
const WIDTH = 2160;

fs.mkdirSync(OUT_DIR, { recursive: true });

// Clear only the files this script owns, so a re-hash never leaves the previous
// one orphaned. Scoped to `.webp` on purpose: the card's cover loop and its
// poster live in the same directory and are not generated here, and an earlier
// version of this line would have deleted them.
for (const f of fs.readdirSync(OUT_DIR)) {
  if (f.endsWith(".webp")) fs.unlinkSync(path.join(OUT_DIR, f));
}

const names = fs
  .readdirSync(SRC)
  .filter((f) => f.endsWith(".png"))
  .sort();

const map = {};
let total = 0;

for (const file of names) {
  const name = file.replace(/\.png$/, "");
  const webp = await sharp(path.join(SRC, file))
    .resize({ width: WIDTH, withoutEnlargement: true })
    .webp({ quality: 82, effort: 6 })
    .toBuffer();

  const hash = crypto.createHash("sha256").update(webp).digest("hex").slice(0, 8);
  const filename = `${name}.${hash}.webp`;
  fs.writeFileSync(path.join(OUT_DIR, filename), webp);

  map[name] = `${PUBLIC_PREFIX}/${filename}`;
  total += webp.length;
  console.log(`${name.padEnd(20)} ${(webp.length / 1024).toFixed(0)}KB  ${filename}`);
}

const body = `/**
 * Real screens from the deployed Nivex prototype, by logical name.
 *
 * Generated by \`scripts/process-nivex-shots.mjs\` — do not hand-edit. The hash
 * in each filename is the file's own content, so re-capturing a screen changes
 * its URL and no cache can serve the previous version. See the script header.
 */
export const nivexShots = {
${Object.entries(map)
  .map(([k, v]) => `  "${k}": "${v}",`)
  .join("\n")}
} as const;

export type NivexShot = keyof typeof nivexShots;
`;

fs.writeFileSync(MANIFEST, body);
console.log("---");
console.log(`${names.length} screens, ${(total / 1024 / 1024).toFixed(2)}MB`);
console.log(`wrote ${MANIFEST}`);
